def read_assignment(path, prefix):
    raw = path.read_text()
    if not raw.startswith(prefix):
        raise ValueError(f"Unexpected data wrapper: {path}")
    return json.loads(raw[len(prefix):].rstrip(" ;\n"))


def write_assignment(path, prefix, data):
    payload = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    path.write_text(f"{prefix}{payload};\n")


def validate_face_data(data):
    errors = []
    tags = data["tags"]
    names = {item["name"] for item in tags}
    name_owners = {item["name"]: item["id"] for item in tags}
    ids = [item["id"] for item in tags]
    tag_names = [item["name"] for item in tags]
    alias_owners = {}

    if len(ids) != len(set(ids)):
        errors.append("标签 ID 存在重复")
    if len(tag_names) != len(set(tag_names)):
        errors.append("标签名称存在重复")

    for item in tags:
        if len(item["definition"]) < 20:
            errors.append(f"{item['id']} {item['name']} 的定义少于 20 字")
        if item["definition"].rstrip("。") not in item["prompt"]:
            errors.append(f"{item['id']} {item['name']} 的 Prompt 未同步最终定义")
        for field in ("id", "part", "dimension", "name", "alias", "en", "type"):
            value = str(item.get(field, ""))
            if value != value.strip() or any(char in value for char in "\n\r\t"):
                errors.append(f"{item['id']} 的 {field} 含首尾或换行空白")
        aliases = [
            value.strip()
            for value in re.split(r"[,，、/；;]+", item.get("alias", ""))
            if value.strip() and value.strip() != "—"
        ]
        for alias in aliases:
            if alias in name_owners and name_owners[alias] != item["id"]:
                errors.append(f"{item['id']} 的别名与其他主标签冲突：{alias}")
            if alias in alias_owners and alias_owners[alias] != item["id"]:
                errors.append(f"{item['id']} 的别名与其他别名重复：{alias}")
            alias_owners[alias] = item["id"]
            if alias not in item["keywords"]:
                errors.append(f"{item['id']} 的别名未同步至关键词：{alias}")

    seen_pairs = set()
    for item in data["confusions"]:
        endpoints = [value.strip() for value in item["pair"].split(" vs ")]
        if len(endpoints) != 2:
            errors.append(f"易混对照格式错误：{item['pair']}")
            continue
        missing = [value for value in endpoints if value not in names]
        if missing:
            errors.append(f"易混对照存在悬空标签：{item['pair']} ({'、'.join(missing)})")
        normalized_pair = tuple(sorted(endpoints))
        if normalized_pair in seen_pairs:
            errors.append(f"易混对照存在正反向重复：{item['pair']}")
        seen_pairs.add(normalized_pair)
        if item["group"] == "其他对照":
            errors.append(f"易混对照未归入正式矩阵：{item['pair']}")

    if errors:
        raise ValueError("\n".join(errors))


