def enrich_shades():
    path = ROOT / "beauty-data.js"
    prefix = "window.BEAUTY_ATLAS_DATA="
    data = read_assignment(path, prefix)
    for item in data["shades"]:
        original = str(item.get("description", "")).strip().rstrip("。")
        if original.startswith("视觉上呈") and "，屏幕参考色为 " in original:
            original = original[len("视觉上呈"):].split("，屏幕参考色为 ", 1)[0]
        visual = original or item["name"]
        family = item.get("family") or item.get("kind") or "综合色系"
        undertone = item.get("undertone") or "未单独标注"
        depth = item.get("depth") or "未单独标注"
        applies = item.get("applies") or "彩妆配色与检索"
        if isinstance(applies, list):
            applies = "、".join(str(value) for value in applies)
        item["description"] = (
            f"视觉上呈{visual}，屏幕参考色为 {item.get('hex', '未标注')}；"
            f"归入{family}，底调为{undertone}、明度层级为{depth}，主要用于{applies}。"
        )
    write_assignment(path, prefix, data)


